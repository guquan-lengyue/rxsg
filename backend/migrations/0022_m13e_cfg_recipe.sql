-- legacy 消费：cfg_recipe（select recipe from cfg_recipe where gid=$targe_gid），
--   recipe 形如 "材料gid,数量,材料gid,数量,..."，由 parseStuffRecipe(1477) 解析为 gid→需求量。
--   重写版此前完全没有 cfg_recipe 表 → 宝石合成无配方可依。
--
-- 【重要·无法确认项】原版 cfg_recipe 的精确内容本地【无权威 dump】（仓库内不存在该表的 .sql / 数据文件），
--   故本文件配方为【合成配方，非原版精确还原】——配方规则如下（与 legacy synthStuff 逻辑自洽）：
--     设目标宝石 gid 的等级为 L：
--       · L=1 的 1 级宝石（300,310,320,330,340,350,360,370）【不能合成】，无配方行；
--       · L≥2 的 300-379（gid%10+1=L）：配方 = "同系低一级宝石×1"，即 recipe="(gid-1),1"；
--       · 17500-17539（gid%5+11=L）：
--           - L=11（gid%5==0）：配方 = "同系 10 级宝石×1"，即 recipe="(base+9),1"（base=300+((gid-17500)/5)*10）；
--           - L≥12（gid%5∈1..4）：配方 = "同系低一级宝石×1"，即 recipe="(gid-1),1"。
--     选择「1 个低一级宝石 → 每次合成尝试」的理由：
--       synthStuff 语义为「count 次合成尝试，消耗 dict[gid]*count 份材料，产出 synth_count(≤count) 个目标」；
--       令每次尝试仅耗 1 份低一级宝石，则「尝试数=投料数、产出≤投料数」完全自洽（成功率决定损耗）。
--     另补 205（强化宝珠）：synthStuff:1194 对其特判「成功率 100%，跳过计算」，属可合成品，故补一行合成配方
--       recipe="300,1"（非原版数值，仅供流程贯通与确定性测试）。
--
-- 【重要·无法确认项】宝石名称（cfg_goods 300-379 / 17500-17539）为【合成名称，非原版精确还原】：
--   沿用 0010_m6_economy.sql 的宝石命名风格（"{前缀}宝石{罗马数字}"），本文件补齐缺失行并补 350 系前缀「精力」。
--   已存在的行【不改动】（INSERT IGNORE，保留 0010 既有名称与 0009 的 attr 列，避免覆盖既有数据）。
--
-- 幂等：CREATE TABLE IF NOT EXISTS + REPLACE INTO(cfg_recipe) + INSERT IGNORE(cfg_goods)。

